export function getProductBySlug(slug: string) {
  return products.find((p) => p.slug === slug);
}

/** Todo produto com foto real — base de qualquer grid/carrossel do catálogo. */
export const visibleProducts = products.filter(hasValidImage);

export function getFeaturedProducts() {
  return visibleProducts.filter((p) => p.featured);
}

/**
 * "Os favoritos da nossa coleção": 1 produto por marca (sem repetir marca),
 * só com foto real. Prioriza os marcados como `featured`; completa com o
 * primeiro produto disponível da marca se ela não tiver nenhum `featured`
 * com foto.
 */
export function getFavoritesOneByBrand(limit = 8) {
  const seenBrands = new Set<string>();
  const result: Product[] = [];

  for (const p of visibleProducts.filter((p) => p.featured)) {
    if (seenBrands.has(p.brand)) continue;
    seenBrands.add(p.brand);
    result.push(p);
  }

  if (result.length < limit) {
    for (const p of visibleProducts) {
      if (result.length >= limit) break;
      if (seenBrands.has(p.brand)) continue;
      seenBrands.add(p.brand);
      result.push(p);
    }
  }

  return result.slice(0, limit);
}

/**
 * "Recém-chegados": os N mais recentes com foto real. Não existe timestamp
 * de cadastro nos dados — usa o `id` numérico (sequencial, maior = mais
 * recente) como proxy, é o único sinal de ordem de cadastro disponível.
 */
export function getNewProducts(limit = 4) {
  return [...visibleProducts]
    .filter((p) => p.isNew)
    .sort((a, b) => Number(b.id) - Number(a.id))
    .slice(0, limit);
}

export function getBrands() {
  return Array.from(new Set(products.map((p) => p.brand))).sort();
}
